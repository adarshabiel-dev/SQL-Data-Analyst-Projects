----- 1. Displaying the customer names along with their corresponding product prices. Showing only those customers who have matching Customer IDs in both tables. -----

select 
	m1.Customer_name,
    m2.Price
from myntra1 m1
inner join myntra2 m2
on m1.Cust_ID = m2.Cust_ID;

----- 2. Displaying all customer names from the first table along with their corresponding product prices from the second table. 
-- Including customers even if they don't have a matching record in the second table. -----

select 
	m1.Customer_Name,
    m2.Price
from myntra1 m1
left join myntra2 m2
on m1.Cust_ID = m2.Cust_ID;

-------- 3. Displaying all product prices from the second table along with the corresponding customer names from the first table. 
-- Including all records from the second table, even if the customer does not exist in the first table. -----

select 
	m1.Customer_Name,
    m2.Price
from myntra1 m1
right join myntra2 m2
on m1.Cust_ID = m2.Cust_ID;

----------- 4. Calculating the total sales amount generated by each customer -------------

select 
	m1.Customer_Name,
    sum(Price) as Total_Sales
from myntra1 m1
inner join myntra2 m2
on m1.Cust_ID = m2.Cust_ID
group by m1.Customer_Name;

----- 5. Assigning an unique row number to every customer based on Product Category, arranging the categories in descending alphabetical order -------

select * from retail_sales;

select 
	Customer_ID,
    Product_Category,
    Total_Amount,
row_number() over(
	order by Product_Category desc
) as row_num
from retail_sales;

----- 6. Assigning an unique row number to customers separately within each Product Category, arranging the product categories in descending alphabetical order.

select 
	Customer_ID,
    Product_Category,
    Total_Amount,
row_number() over(
	partition by Product_Category
	order by Product_Category desc
) as row_num
from retail_sales;

-------- 7. Ranking all customers based on their Total Amount, starting with the highest spending customer. 
----- If two or more customers have the same Total Amount, assign them the same rank.-------------------

select * from retail_sales;

select
	Customer_ID,
    Total_Amount,
Rank() Over(
	order by Total_Amount desc
    ) as Amount_Rank
from retail_sales;

----- 8. Ranking customers separately within each Product Category based on their Total Amount, starting with the highest spending customer in each category.-----

select
	Customer_ID,
    Total_Amount,
    Product_Category,
Rank() Over(
partition by Product_Category
	order by Total_Amount desc
    ) as Amount_Rank
from retail_sales;

----- 9. Assign a dense rank to all customers based on their Total Amount, starting with the highest-spending customer. 
----- If two or more customers have the same Total Amount, assign them the same rank without skipping the next rank. -------

select
	Customer_ID,
    Total_Amount,
dense_rank() Over(
	order by Total_Amount desc
    ) as Amount_Rank
from retail_sales;


----- 10. Assign a dense rank to customers separately within each Product Category based on their Total Amount, starting with the highest-spending customer in each category. 
----- If customers have the same spending amount, assign them the same rank without skipping the next rank.----
select
	Customer_ID,
    Total_Amount,
    Product_Category,
Dense_Rank() Over(
partition by Product_Category
	order by Total_Amount desc
    ) as Amount_Rank
from retail_sales;

